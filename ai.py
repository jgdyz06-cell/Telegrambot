# ============================================================
# Check Configuration
# ============================================================

def check_gemini_config():

    if not GEMINI_API_KEY:
        return (
            False,
            "GEMINI_API_KEY غير موجود في Railway Variables."
        )

    if client is None:
        return (
            False,
            "تعذر إنشاء اتصال Gemini."
        )

    return (
        True,
        "Gemini جاهز."
    )


# ============================================================
# Check 503
# ============================================================

def is_503_error(error):

    text = str(error).upper()

    return (
        "503" in text
        or "UNAVAILABLE" in text
        or "SERVICE UNAVAILABLE" in text
    )


# ============================================================
# Generate
# ============================================================

def _generate_with_model(
    model,
    prompt
):

    if client is None:

        raise RuntimeError(
            "Gemini client غير جاهز."
        )

    logger.info(
        "Trying Gemini model: %s",
        model
    )

    full_prompt = (
        SYSTEM_PROMPT
        + "\n\n"
        + prompt
    )

    response = client.models.generate_content(

        model=model,

        contents=full_prompt,

        config=types.GenerateContentConfig(

            max_output_tokens=3000

        )
    )

    if not response:

        raise RuntimeError(
            "Gemini أعاد استجابة فارغة."
        )

    result = getattr(
        response,
        "text",
        None
    )

    if not result:

        raise RuntimeError(
            "Gemini لم يرجع نصاً."
        )

    return result.strip()


# ============================================================
# Main Generate
# ============================================================

def _generate(prompt):

    if not GEMINI_API_KEY:

        raise RuntimeError(
            "مفتاح Gemini غير موجود."
        )

    if client is None:

        raise RuntimeError(
            "تعذر الاتصال بخدمة Gemini."
        )

    last_error = None

    # تجربة الموديلات مباشرة بدون انتظار
    for model in FALLBACK_MODELS:

        try:

            return _generate_with_model(
                model,
                prompt
            )

        except Exception as error:

            last_error = error

            if is_503_error(error):

                logger.warning(
                    "Model %s returned 503. "
                    "Trying next model immediately.",
                    model
                )

                continue

            logger.exception(
                "Gemini request failed."
            )

            raise RuntimeError(
                f"Gemini error: {error}"
            ) from error

    # فشل الموديلين
    raise RuntimeError(
        "Gemini مشغول حالياً وأعاد 503."
    ) from last_error


# ============================================================
# Public AI Function
# ============================================================

async def ask_ai(
    mode,
    text
):

    # ----------------------------------------
    # فحص النص
    # ----------------------------------------

    if not text or not text.strip():

        return (
            "❌ ما وصلني نص للتحليل.\n\n"
            "أرسل النص أولاً ثم اختر نوع التحليل."
        )

    # ----------------------------------------
    # فحص Gemini
    # ----------------------------------------

    ok, message = check_gemini_config()

    if not ok:

        logger.error(
            "Gemini configuration error: %s",
            message
        )

        return (
            "❌ تعذر تشغيل الذكاء الاصطناعي حالياً.\n\n"
            + message
        )

    # ----------------------------------------
    # تحديد نوع التحليل
    # ----------------------------------------

    if mode not in PROMPTS:

        mode = "explain"

    # ----------------------------------------
    # بناء الطلب
    # ----------------------------------------

    prompt = (
        PROMPTS[mode]
        + "\n\n"
        + text.strip()
    )

    # ----------------------------------------
    # إرسال الطلب
    # ----------------------------------------

    try:

        result = await asyncio.to_thread(
            _generate,
            prompt
        )

        if not result:

            return (
                "❌ Gemini لم يرجع نتيجة."
            )

        return result

    except Exception as error:

        logger.exception(
            "AI request failed."
        )

        if is_503_error(error):

            return (
                "⚠️ Gemini مشغول حالياً.\n\n"
                "حاول مرة ثانية بعد قليل 🔄"
            )

        return (
            "❌ حدث خطأ أثناء تحليل النص.\n\n"
            f"التفاصيل: {error}"
        )


