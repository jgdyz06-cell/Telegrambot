def _generate(prompt: str) -> str:

    if not GEMINI_API_KEY:
        raise RuntimeError(
            "لم يتم العثور على GEMINI_API_KEY في Railway Variables."
        )

    client = genai.Client(
        api_key=GEMINI_API_KEY
    )

    response = client.models.generate_content(
        model=GEMINI_MODEL,
        contents=prompt,
        config=types.GenerateContentConfig(
            system_instruction=SYSTEM_PROMPT,
            max_output_tokens=2500,
        ),
    )

    result = getattr(response, "text", None)

    if not result:
        raise RuntimeError(
            "Gemini لم يرجع نصاً."
        )

    return result.strip()


async def ask_ai(text: str, mode: str) -> str:

    instruction = PROMPTS.get(mode)

    if not instruction:
        instruction = """
حلل النص التالي تحليلاً لغوياً وتعليمياً مفيداً للطالب:
"""

    prompt = (
        instruction
        + "\n\n"
        + text
    )

    return await asyncio.to_thread(
        _generate,
        prompt
)
