# ============================================================
# القائمة الرئيسية للقواعد
# ============================================================

def rules_menu():

    rows = []

    for rule_id, rule in RULES.items():

        rows.append(
            [
                InlineKeyboardButton(
                    rule["title"],
                    callback_data=f"rule:{rule_id}",
                )
            ]
        )

    rows.append(
        [
            InlineKeyboardButton(
                "🎲 قاعدة عشوائية",
                callback_data="rule:random",
            )
        ]
    )

    rows.append(
        [
            InlineKeyboardButton(
                "🏠 القائمة الرئيسية",
                callback_data="m",
            )
        ]
    )

    return InlineKeyboardMarkup(rows)


# ============================================================
# قائمة القاعدة
# ============================================================

def rule_markup():

    return InlineKeyboardMarkup(
        [
            [
                InlineKeyboardButton(
                    "🎲 قاعدة عشوائية",
                    callback_data="rule:random",
                )
            ],
            [
                InlineKeyboardButton(
                    "📚 كل القواعد",
                    callback_data="rules",
                )
            ],
            [
                InlineKeyboardButton(
                    "🏠 القائمة الرئيسية",
                    callback_data="m",
                )
            ],
        ]
    )


# ============================================================
# الحصول على قاعدة عشوائية
# ============================================================

def random_rule():

    import random

    rule_id = random.choice(
        list(RULES.keys())
    )

    return rule_id, RULES[rule_id]


# ============================================================
# عرض القائمة
# ============================================================

async def show_rules(q):

    await q.edit_message_text(

        "📚 **شرح قواعد اللغة العربية**\n\n"
        "اختر القاعدة التي تريد شرحها:",

        parse_mode="Markdown",

        reply_markup=rules_menu(),

    )


# ============================================================
# عرض قاعدة
# ============================================================

async def show_rule(
    q,
    rule_id,
):

    if rule_id == "random":

        _, rule = random_rule()

    else:

        rule = RULES.get(
            rule_id
        )

    if not rule:

        await q.edit_message_text(
            "❌ القاعدة غير موجودة.",
            reply_markup=rules_menu(),
        )

        return

    await q.edit_message_text(

        rule["text"].strip(),

        reply_markup=rule_markup(),

    )
